def metadata_value(record: Mapping[str, Any], patterns: Sequence[str]) -> str:
    values: list[str] = []
    for key, value in record.items():
        low = key.lower()
        if any(pattern in low for pattern in patterns):
            text = normalize_space(value)
            if text and text not in values and len(text) < 250:
                values.append(text)
    return " | ".join(values[:8])


def record_candidate_url(record: Mapping[str, Any]) -> str:
    candidate = normalize_space(record.get("_candidate_url", ""))
    if candidate:
        try:
            candidate = canonical_url(candidate)
        except Exception:
            candidate = ""
    if candidate and is_library_url(candidate):
        return candidate
    slug = metadata_value(record, (".slug", "slug", ".alias", "alias", ".code", "code"))
    slug = slug.split(" | ")[0].strip()
    if re.fullmatch(r"[A-Za-zА-Яа-яЁё0-9_.~-]{2,160}", slug):
        return canonical_url(f"{LIBRARY_URL}/{slug}")
    return ""


def record_dimension_value(record: Mapping[str, Any], dimension: str) -> str:
    """Extract one taxonomy value without swallowing an entire nested catalogue."""
    context_key = f"_context_{dimension}"
    direct = normalize_space(record.get(context_key, ""))
    if direct and len(direct) <= 180:
        return direct

    aliases: dict[str, tuple[str, ...]] = {
        "industry": ("industry", "sector", "sphere", "branch", "отрасл"),
        "business_function": (
            "business_function",
            "businessfunction",
            "biz_function",
            "function.title",
            "function.name",
            "функци",
        ),
        "business_task": (
            "business_task",
            "businesstask",
            "biz_task",
            "task.title",
            "task.name",
            "задач",
        ),
    }
    candidates: list[tuple[int, str]] = []
    for key, value in record.items():
        low = str(key).lower()
        if not any(alias in low for alias in aliases[dimension]):
            continue
        text = normalize_space(value)
        if not text or len(text) > 180 or text.startswith("http"):
            continue
        score = 0
        if low == context_key:
            score += 100
        if any(low.endswith(suffix) for suffix in (".title", ".name", ".label", ".value", ".slug")):
            score += 20
        if low.endswith(".id") or re.fullmatch(r"\d+", text):
            score -= 10
        candidates.append((score, text))
    if not candidates:
        return ""
    candidates.sort(key=lambda item: (-item[0], len(item[1]), item[1]))
    return candidates[0][1]


def merge_network_metadata(cards: list[Card], records: Sequence[Mapping[str, Any]]) -> None:
    """Attach all distinct taxonomy labels to cards, without losing multi-cell reuse."""
    by_slug: dict[str, list[Mapping[str, Any]]] = defaultdict(list)
    for record in records:
        candidate_url = record_candidate_url(record)
        slug = slug_from_url(candidate_url).lower() if candidate_url else ""
        if slug:
            by_slug[slug].append(record)

    for card in cards:
        candidates = by_slug.get(card.slug.lower(), [])
        if not candidates:
            continue
        values: dict[str, set[str]] = {
            "industry": set(),
            "business_function": set(),
            "business_task": set(),
        }
        for record in candidates:
            for dimension in values:
                value = record_dimension_value(record, dimension)
                if value:
                    values[dimension].add(value)
        card.industry = " | ".join(sorted(values["industry"]))
        card.business_function = " | ".join(sorted(values["business_function"]))
        card.business_task = " | ".join(sorted(values["business_task"]))


def taxonomy_placements(
    records: Sequence[Mapping[str, Any]], cards: Sequence[Card]
) -> list[dict[str, Any]]:
    """Return unique card placements in industry × function × task cells.

    The same URL may legitimately appear in many records/endpoints. `observation_count` preserves
    that fact while the output has one row per unique placement tuple.
    """
    by_url = {card.url: card for card in cards}
    by_slug = {card.slug.lower(): card for card in cards}
    groups: dict[tuple[str, str, str, str], dict[str, Any]] = {}
    for record in records:
        url = record_candidate_url(record)
        if not url:
            continue
        card = by_url.get(url) or by_slug.get(slug_from_url(url).lower())
        industry = record_dimension_value(record, "industry")
        function = record_dimension_value(record, "business_function")
        task = record_dimension_value(record, "business_task")
        if not (industry or function or task):
            continue
        source = normalize_space(record.get("_source", "network-json")) or "network-json"
        key = (url, industry, function, task)
        row = groups.setdefault(
            key,
            {
                "url": url,
                "slug": slug_from_url(url),
                "title": card.title if card else metadata_value(record, (".title", "title", ".name", "name")),
                "grade": card.grade if card else "not_fetched",
                "source_family": card.source_family if card else "not_fetched",
                "content_hash": card.content_hash if card else "",
                "industry": industry,
                "business_function": function,
                "business_task": task,
                "observation_count": 0,
                "observation_sources": set(),
            },
        )
        row["observation_count"] += 1
        row["observation_sources"].add(source)

    output: list[dict[str, Any]] = []
    for row in groups.values():
        clean = dict(row)
        clean["observation_sources"] = " | ".join(sorted(row["observation_sources"]))
        output.append(clean)
    return sorted(
        output,
        key=lambda row: (
            str(row["industry"]),
            str(row["business_function"]),
            str(row["business_task"]),
            str(row["url"]),
        ),
    )


