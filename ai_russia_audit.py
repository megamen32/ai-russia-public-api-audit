async def download_casebook(client: PoliteClient, out_dir: Path, enabled: bool) -> tuple[str, dict[str, Any]]:
    if not enabled:
        return "", {"disabled": True}
    pdf_path = out_dir / "sources" / "AI_Alliance_Casebook2024.pdf"
    pdf_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        if pdf_path.exists() and pdf_path.stat().st_size > 100_000:
            data = pdf_path.read_bytes()
        else:
            response = await client.get(CASEBOOK_URL)
            response.raise_for_status()
            data = response.content
            pdf_path.write_bytes(data)
        return extract_casebook_fingerprint(data)
    except Exception as exc:
        logging.warning("Casebook download/parse failed: %s", exc)
        return "", {"error": str(exc)}


async def fetch_one_card(
    record: DiscoveryRecord,
    client: PoliteClient,
    renderer: BrowserRenderer | None,
    raw_html_dir: Path,
    cache_dir: Path,
    *,
    use_jina: bool,
    resume: bool,
) -> Card | None:
    slug = safe_filename(slug_from_url(record.url))
    cache_path = cache_dir / f"{slug}.json"
    if resume and cache_path.exists():
        try:
            data = json.loads(cache_path.read_text(encoding="utf-8"))
            return Card(**data)
        except Exception:
            pass

    html = ""
    status = 0
    final_url = record.url
    try:
        response = await client.get(record.url)
        status = response.status_code
        final_url = str(response.url)
        content_type = (response.headers.get("content-type") or "").lower()
        if response.status_code == 200 and "html" in content_type:
            html = response.text
            card = parse_card_html(
                html,
                final_url,
                discovery_sources=record.sources,
                status_code=status,
                fetch_method="httpx",
            )
            if card is not None:
                raw_path = raw_html_dir / f"{slug}.html"
                raw_path.write_text(html, encoding="utf-8")
                card.raw_html_path = str(raw_path)
                cache_path.write_text(json.dumps(card_to_dict(card), ensure_ascii=False, indent=2), encoding="utf-8")
                return card
        if response.status_code in {404, 410}:
            return None
    except Exception as exc:
        logging.debug("Direct fetch failed %s: %s", record.url, exc)

    if renderer is not None:
        try:
            html, status, final_url = await renderer.render(record.url)
            card = parse_card_html(
                html,
                final_url,
                discovery_sources=record.sources,
                status_code=status,
                fetch_method="playwright",
            )
            if card is not None:
                raw_path = raw_html_dir / f"{slug}.html"
                raw_path.write_text(html, encoding="utf-8")
                card.raw_html_path = str(raw_path)
                cache_path.write_text(json.dumps(card_to_dict(card), ensure_ascii=False, indent=2), encoding="utf-8")
                return card
        except Exception as exc:
            logging.debug("Playwright render failed %s: %s", record.url, exc)

    if use_jina:
        reader_url = "https://r.jina.ai/" + record.url
        try:
            response = await client.get(reader_url, headers={"X-Return-Format": "markdown"})
            if response.status_code == 200:
                card = parse_card_markdown(
                    response.text,
                    record.url,
                    discovery_sources=record.sources,
                    status_code=response.status_code,
                )
                if card is not None:
                    raw_path = raw_html_dir / f"{slug}.md"
                    raw_path.write_text(response.text, encoding="utf-8")
                    card.raw_html_path = str(raw_path)
                    cache_path.write_text(
                        json.dumps(card_to_dict(card), ensure_ascii=False, indent=2), encoding="utf-8"
                    )
                    return card
        except Exception as exc:
            logging.debug("Jina Reader failed %s: %s", record.url, exc)
    return None


async def fetch_cards(
    discovery: Mapping[str, DiscoveryRecord],
    client: PoliteClient,
    renderer: BrowserRenderer | None,
    out_dir: Path,
    *,
    concurrency: int,
    max_pages: int,
    use_jina: bool,
    resume: bool,
    robots: urllib.robotparser.RobotFileParser | None,
    ignore_robots: bool,
    user_agent: str,
) -> list[Card]:
    raw_html_dir = out_dir / "raw" / "pages"
    cache_dir = out_dir / "cache" / "cards"
    raw_html_dir.mkdir(parents=True, exist_ok=True)
    cache_dir.mkdir(parents=True, exist_ok=True)

    candidates = sorted(discovery.values(), key=lambda item: item.url)
    # Root/category pages are still tested, but place likely cards first.
    candidates.sort(
        key=lambda item: (
            slug_from_url(item.url).lower() in CATEGORY_SLUG_HINTS,
            not bool(re.fullmatch(r"(?:ml|genai)\d+", slug_from_url(item.url).lower())),
            item.url,
        )
    )
    if max_pages > 0:
        candidates = candidates[:max_pages]

    semaphore = asyncio.Semaphore(max(1, concurrency))
    cards: list[Card] = []
    counter = 0
    counter_lock = asyncio.Lock()

    async def worker(item: DiscoveryRecord) -> None:
        nonlocal counter
        if robots is not None and not ignore_robots and not robots.can_fetch(user_agent, item.url):
            logging.warning("robots.txt disallows %s; skipped", item.url)
            return
        async with semaphore:
            card = await fetch_one_card(
                item,
                client,
                renderer,
                raw_html_dir,
                cache_dir,
                use_jina=use_jina,
                resume=resume,
            )
        async with counter_lock:
            counter += 1
            if counter % 25 == 0 or counter == len(candidates):
                logging.info("Fetched/validated %d/%d candidates; cards=%d", counter, len(candidates), len(cards))
        if card is not None:
            cards.append(card)

    await asyncio.gather(*(worker(item) for item in candidates))
    # Canonical URL deduplication; keep the richest parse.
    best: dict[str, Card] = {}
    for card in cards:
        previous = best.get(card.url)
        richness = len(card.full_text) + 500 * sum(
            is_nonempty(value)
            for value in (card.adopter, card.results, card.business_effect, card.team, card.technologies)
        )
        previous_richness = -1
        if previous is not None:
            previous_richness = len(previous.full_text) + 500 * sum(
                is_nonempty(value)
                for value in (
                    previous.adopter,
                    previous.results,
                    previous.business_effect,
                    previous.team,
                    previous.technologies,
                )
            )
        if previous is None or richness > previous_richness:
            best[card.url] = card
    return sorted(best.values(), key=lambda card: (card.visible_number or "999999", card.slug.lower()))


async def main_async(args: argparse.Namespace) -> int:
    out_dir = Path(args.out).expanduser().resolve()
    (out_dir / "raw" / "discovery").mkdir(parents=True, exist_ok=True)
    logging.info("Output: %s", out_dir)

    discovery: dict[str, DiscoveryRecord] = {}
    network_records: list[dict[str, Any]] = []
    endpoint_rows: list[dict[str, Any]] = []

    # User-supplied URLs are useful when the site changes or an internal export exists.
    if args.urls_file:
        for line in Path(args.urls_file).read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                add_discovery(discovery, line, "urls-file")

    async with PoliteClient(
        timeout=args.timeout,
        delay=args.delay,
        user_agent=args.user_agent,
        verify=not args.insecure,
    ) as client:
        robots_text, robots_parser = await fetch_robots(client)
        if robots_text:
            (out_dir / "raw" / "discovery" / "robots.txt").write_text(robots_text, encoding="utf-8")

        casebook_normalized, fingerprint = await download_casebook(client, out_dir, not args.no_casebook)

        if not args.no_sitemap:
            await discover_from_sitemaps(
                client,
                discovery,
                robots_text,
                out_dir / "raw" / "discovery",
            )
        if not args.no_history:
            await discover_from_common_crawl(
                client,
                discovery,
                out_dir / "raw" / "discovery",
                indexes=args.common_crawl_indexes,
            )
            await discover_from_wayback(
                client,
                discovery,
                out_dir / "raw" / "discovery",
            )
        if args.seed_max > 0:
            seed_catalog_urls(discovery, args.seed_max)

        if not args.no_browser_discovery:
            endpoint_rows = await discover_with_browser(
                discovery,
                network_records,
                out_dir / "raw" / "discovery",
                headless=not args.headful,
                user_agent=args.user_agent,
                timeout_ms=int(args.timeout * 1000),
                max_pages=args.browser_discovery_pages,
            )

        # Persist discovery before the expensive card fetch.
        discovery_rows = [
            {"url": record.url, "sources": " | ".join(sorted(record.sources))}
            for record in sorted(discovery.values(), key=lambda item: item.url)
        ]
        write_csv(out_dir / "discovery_sources.csv", discovery_rows)
        write_csv(out_dir / "network_endpoints.csv", endpoint_rows)
        with (out_dir / "network_records.jsonl").open("w", encoding="utf-8") as handle:
            for record in network_records:
                handle.write(json.dumps(record, ensure_ascii=False) + "\n")

        logging.info("Discovered %d candidate URLs", len(discovery))
        renderer_context: BrowserRenderer | None = None
        if not args.no_browser_fetch:
            try:
                renderer_context = BrowserRenderer(
                    headless=not args.headful,
                    concurrency=args.browser_concurrency,
                    user_agent=args.user_agent,
                    timeout_ms=int(args.timeout * 1000),
                )
                await renderer_context.__aenter__()
            except Exception as exc:
                logging.warning("Browser fetch disabled after startup failure: %s", exc)
                renderer_context = None

        try:
            cards = await fetch_cards(
                discovery,
                client,
                renderer_context,
                out_dir,
                concurrency=args.concurrency,
                max_pages=args.max_pages,
                use_jina=args.use_jina,
                resume=args.resume,
                robots=robots_parser,
                ignore_robots=args.ignore_robots,
                user_agent=args.user_agent,
            )
        finally:
            if renderer_context is not None:
                await renderer_context.__aexit__(None, None, None)

    merge_network_metadata(cards, network_records)
    for card in cards:
        classify_card(card, casebook_normalized)

    rows = [card_to_dict(card) for card in cards]
    write_csv(out_dir / "all_cards.csv", rows)
    with (out_dir / "all_cards.jsonl").open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")

    real = [row for row in rows if row["grade"] in {"A_source_backed_implemented", "B_documented_implemented"}]
    named = [row for row in rows if row["grade"] == "C_named_but_weakly_evidenced"]
    scenarios = [row for row in rows if row["grade"] == "D_scenario_or_potential"]
    manual = [row for row in rows if row["grade"] in {"C_named_but_weakly_evidenced", "E_unclear"}]
    write_csv(out_dir / "real_candidates.csv", real, fieldnames=list(rows[0].keys()) if rows else None)
    write_csv(out_dir / "named_weak_claims.csv", named, fieldnames=list(rows[0].keys()) if rows else None)
    write_csv(out_dir / "catalog_scenarios.csv", scenarios, fieldnames=list(rows[0].keys()) if rows else None)
    write_csv(out_dir / "manual_review.csv", manual, fieldnames=list(rows[0].keys()) if rows else None)

    exact = exact_duplicate_groups(cards)
    near = near_duplicate_pairs(cards, threshold=args.duplicate_threshold, neighbours=args.duplicate_neighbours)
    openings = sentence_openings(cards)
    placements = taxonomy_placements(network_records, cards)
    reuse = placement_reuse_rows(placements)
    matrix = (
        matrix_counts_from_placements(placements, cards)
        if placements
        else matrix_counts_from_cards(cards)
    )
    verification = make_verification_queries(cards)
    write_csv(out_dir / "exact_duplicate_groups.csv", exact)
    write_csv(out_dir / "near_duplicate_pairs.csv", near)
    write_csv(out_dir / "repeated_sentence_openings.csv", openings)
    write_csv(out_dir / "taxonomy_placements.csv", placements)
    write_csv(out_dir / "placement_reuse.csv", reuse)
    write_csv(out_dir / "matrix_counts.csv", matrix)
    write_csv(out_dir / "verification_queries.csv", verification)

    (out_dir / "casebook_fingerprint.json").write_text(
        json.dumps(fingerprint, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    report = render_report(cards, discovery, fingerprint, exact, near, matrix, placements, reuse)
    (out_dir / "report.md").write_text(report, encoding="utf-8")

    print(report)
    logging.info("Done. Main files: %s, %s", out_dir / "report.md", out_dir / "real_candidates.csv")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Enumerate and audit AI Russia library cards without treating site counters as unique cases.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--out", default="ai_russia_audit_output", help="Output directory")
    parser.add_argument("--urls-file", help="Optional newline-separated URL list to merge into discovery")
    parser.add_argument("--max-pages", type=int, default=0, help="Limit validated candidates; 0 means unlimited")
    parser.add_argument("--seed-max", type=int, default=130, help="Probe ml001..N and genai001..N")
    parser.add_argument("--browser-discovery-pages", type=int, default=24, help="Taxonomy pages visited for XHR/link discovery")
    parser.add_argument("--common-crawl-indexes", type=int, default=3, help="Newest Common Crawl indexes queried")
    parser.add_argument("--concurrency", type=int, default=3, help="Concurrent candidate workers")
    parser.add_argument("--browser-concurrency", type=int, default=2, help="Concurrent rendered card pages")
    parser.add_argument("--delay", type=float, default=0.45, help="Global delay between direct HTTP requests")
    parser.add_argument("--timeout", type=float, default=30.0, help="HTTP/browser timeout in seconds")
    parser.add_argument("--duplicate-threshold", type=float, default=0.86, help="Near-duplicate cosine threshold")
    parser.add_argument("--duplicate-neighbours", type=int, default=6, help="Nearest neighbours tested per card")
    parser.add_argument("--user-agent", default=DEFAULT_USER_AGENT)
    parser.add_argument("--headful", action="store_true", help="Show Chromium window")
    parser.add_argument("--resume", action=argparse.BooleanOptionalAction, default=True, help="Reuse per-card cache")
    parser.add_argument("--use-jina", action=argparse.BooleanOptionalAction, default=False, help="Use Jina Reader as final fallback")
    parser.add_argument("--no-sitemap", action="store_true")
    parser.add_argument("--no-history", action="store_true", help="Skip Common Crawl and Wayback URL discovery")
    parser.add_argument("--no-browser-discovery", action="store_true")
    parser.add_argument("--no-browser-fetch", action="store_true")
    parser.add_argument("--no-casebook", action="store_true")
    parser.add_argument("--ignore-robots", action="store_true", help="Ignore robots.txt (not recommended)")
    parser.add_argument("--insecure", action="store_true", help="Disable TLS verification (not recommended)")
    parser.add_argument("--verbose", action="store_true")
    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
    )
    try:
        return asyncio.run(main_async(args))
    except KeyboardInterrupt:
        logging.warning("Interrupted; cached cards and discovery files remain reusable with --resume")
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
