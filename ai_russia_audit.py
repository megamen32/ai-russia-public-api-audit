class PoliteClient:
    """A tiny globally rate-limited wrapper around httpx.AsyncClient."""

    def __init__(
        self,
        *,
        timeout: float,
        delay: float,
        user_agent: str,
        verify: bool = True,
    ) -> None:
        self.delay = max(0.0, delay)
        self._last_request = 0.0
        self._lock = asyncio.Lock()
        self.client = httpx.AsyncClient(
            timeout=httpx.Timeout(timeout),
            follow_redirects=True,
            headers={
                "User-Agent": user_agent,
                "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,application/json;q=0.8,*/*;q=0.5",
                "Accept-Language": "ru,en;q=0.7",
            },
            verify=verify,
        )

    async def __aenter__(self) -> "PoliteClient":
        return self

    async def __aexit__(self, exc_type: Any, exc: Any, tb: Any) -> None:
        await self.client.aclose()

    async def get(self, url: str, **kwargs: Any) -> httpx.Response:
        async with self._lock:
            elapsed = time.monotonic() - self._last_request
            if elapsed < self.delay:
                await asyncio.sleep(self.delay - elapsed)
            response = await self.client.get(url, **kwargs)
            self._last_request = time.monotonic()
            return response


class BrowserRenderer:
    def __init__(
        self,
        *,
        headless: bool,
        concurrency: int,
        user_agent: str,
        timeout_ms: int,
    ) -> None:
        self.headless = headless
        self.semaphore = asyncio.Semaphore(max(1, concurrency))
        self.user_agent = user_agent
        self.timeout_ms = timeout_ms
        self._pw: Any = None
        self._browser: Browser | None = None
        self._context: BrowserContext | None = None

    async def __aenter__(self) -> "BrowserRenderer":
        if async_playwright is None:
            raise RuntimeError(
                "Playwright is not installed. Run: pip install playwright && playwright install chromium"
            )
        self._pw = await async_playwright().start()
        self._browser = await self._pw.chromium.launch(headless=self.headless)
        self._context = await self._browser.new_context(
            user_agent=self.user_agent,
            locale="ru-RU",
            viewport={"width": 1440, "height": 1000},
        )
        self._context.set_default_timeout(self.timeout_ms)
        return self

    async def __aexit__(self, exc_type: Any, exc: Any, tb: Any) -> None:
        if self._context is not None:
            await self._context.close()
        if self._browser is not None:
            await self._browser.close()
        if self._pw is not None:
            await self._pw.stop()

    async def render(self, url: str) -> tuple[str, int, str]:
        if self._context is None:
            raise RuntimeError("BrowserRenderer has not been entered")
        async with self.semaphore:
            page = await self._context.new_page()
            try:
                response = await page.goto(url, wait_until="domcontentloaded")
                try:
                    await page.wait_for_load_state("networkidle", timeout=min(8000, self.timeout_ms))
                except Exception:
                    pass
                await progressive_scroll(page, rounds=5)
                html = await page.content()
                status = response.status if response is not None else 0
                final_url = page.url
                return html, status, final_url
            finally:
                await page.close()


def normalize_space(value: Any) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def normalize_for_match(value: str) -> str:
    value = value.lower().replace("ё", "е")
    value = value.replace("‐", "-").replace("‑", "-").replace("–", "-").replace("—", "-")
    value = re.sub(r"-\s+", "", value)  # PDF line-break hyphenation
    value = re.sub(r"[^0-9a-zа-я]+", "", value)
    return value


def normalized_text_hash(value: str) -> str:
    compact = normalize_for_match(value)
    return hashlib.sha256(compact.encode("utf-8")).hexdigest()


def canonical_url(url: str, base: str = BASE_URL) -> str:
    url = urllib.parse.urljoin(base, url)
    parsed = urllib.parse.urlsplit(url)
    host = parsed.netloc.lower()
    if host.startswith("www."):
        host = host[4:]
    if host == "stage.ai-russia.ru":
        host = "ai-russia.ru"
    path = re.sub(r"/{2,}", "/", parsed.path).rstrip("/") or "/"
    return urllib.parse.urlunsplit(("https", host, path, "", ""))


def slug_from_url(url: str) -> str:
    return urllib.parse.unquote(urllib.parse.urlsplit(url).path.rstrip("/").split("/")[-1])


def is_library_url(url: str) -> bool:
    parsed = urllib.parse.urlsplit(url)
    return parsed.netloc.lower().removeprefix("www.") in {"ai-russia.ru", "stage.ai-russia.ru"} and parsed.path.startswith(
        "/library/"
    )


def is_legacy_index_url(url: str) -> bool:
    parsed = urllib.parse.urlsplit(url)
    host_ok = parsed.netloc.lower().removeprefix("www.") in {"ai-russia.ru", "stage.ai-russia.ru"}
    return host_ok and bool(re.fullmatch(r"/case/(?:2018|2019|2020|2021)/?", parsed.path))


def looks_like_card_text(text: str, title: str = "") -> bool:
    low = text.lower()
    marker_count = sum(marker in low for marker in CARD_MARKERS)
    generic_title = title.lower().strip() in {
        "витрина ии-кейсов",
        "витрина кейсов",
        "ai russia",
        "библиотека",
    }
    return not generic_title and marker_count >= 2 and len(text) >= 160


def is_nonempty(value: str) -> bool:
    value = normalize_space(value)
    if len(value) < 2:
        return False
    return not any(re.fullmatch(pattern, value, re.IGNORECASE) for pattern in EMPTY_VALUE_PATTERNS)


def safe_filename(value: str, max_len: int = 110) -> str:
    value = re.sub(r"[^0-9A-Za-zА-Яа-яЁё._-]+", "_", value).strip("._")
    return (value[:max_len] or "item")


def add_discovery(store: MutableMapping[str, DiscoveryRecord], url: str, source: str) -> None:
    try:
        url = canonical_url(url)
    except Exception:
        return
    if not is_library_url(url):
        return
    record = store.setdefault(url, DiscoveryRecord(url=url))
    record.sources.add(source)


def iter_strings(obj: Any) -> Iterator[str]:
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, Mapping):
        for key, value in obj.items():
            yield str(key)
            yield from iter_strings(value)
    elif isinstance(obj, Sequence) and not isinstance(obj, (str, bytes, bytearray)):
        for value in obj:
            yield from iter_strings(value)


def leaf_text(value: Any, max_items: int = 20) -> str:
    values: list[str] = []
    for item in iter_strings(value):
        item = normalize_space(item)
        if item and item not in values:
            values.append(item)
        if len(values) >= max_items:
            break
    return " | ".join(values)


def flatten_keys(obj: Any, prefix: str = "", depth: int = 0, max_depth: int = 4) -> dict[str, Any]:
    out: dict[str, Any] = {}
    if depth > max_depth:
        return out
    if isinstance(obj, Mapping):
        for key, value in obj.items():
            path = f"{prefix}.{key}" if prefix else str(key)
            if isinstance(value, (str, int, float, bool)) or value is None:
                out[path.lower()] = value
            else:
                out.update(flatten_keys(value, path, depth + 1, max_depth))
    elif isinstance(obj, Sequence) and not isinstance(obj, (str, bytes, bytearray)):
        for index, value in enumerate(obj[:30]):
            out.update(flatten_keys(value, f"{prefix}[{index}]", depth + 1, max_depth))
    return out


def dimension_from_key(key: str) -> str | None:
    cleaned = re.sub(r"\[\d+\]", "", str(key).lower())
    for dimension, pattern in DIMENSION_KEY_RE.items():
        if pattern.search(cleaned):
            return dimension
    return None


def compact_dimension_value(value: Any) -> str:
    """Return a short human-readable taxonomy value, never a whole nested catalogue."""
    if isinstance(value, Mapping):
        lower = {str(key).lower(): key for key in value}
        for wanted in DIMENSION_VALUE_KEYS:
            source_key = lower.get(wanted)
            if source_key is None:
                continue
            candidate = value[source_key]
            if isinstance(candidate, (str, int, float)) and not isinstance(candidate, bool):
                text = normalize_space(candidate)
                if 0 < len(text) <= 120:
                    return text
        return ""
    if isinstance(value, (str, int, float)) and not isinstance(value, bool):
        text = normalize_space(value)
        if 0 < len(text) <= 120:
            return text
    return ""


def extract_urls_and_records_from_json(
    obj: Any,
    store: MutableMapping[str, DiscoveryRecord],
    source: str,
    records: list[dict[str, Any]],
    *,
    inherited_context: Mapping[str, str] | None = None,
    forced_dimension: str | None = None,
) -> None:
    """Recursively pull library URLs and card records from arbitrary SPA/API JSON.

    Taxonomy values are inherited down the JSON tree. This matters when an endpoint is shaped like
    `industry -> function -> task -> cards`: each card then keeps the exact matrix cell from which
    it came instead of being flattened into one lossy list of tags.
    """

    context = dict(inherited_context or {})

    if isinstance(obj, str):
        for path in LIBRARY_PATH_RE.findall(obj):
            add_discovery(store, path, source)
        return

    if isinstance(obj, Mapping):
        if forced_dimension:
            forced_value = compact_dimension_value(obj)
            if forced_value:
                context[forced_dimension] = forced_value

        # Direct scalar/mapping dimension fields on the current object. Sequences are handled item
        # by item below so one industry cannot leak into the next.
        for raw_key, value in obj.items():
            dimension = dimension_from_key(str(raw_key))
            if dimension and not isinstance(value, Sequence):
                candidate = compact_dimension_value(value)
                if candidate:
                    context[dimension] = candidate

        lower_keys = {str(k).lower(): k for k in obj.keys()}
        title_key = next((lower_keys[k] for k in ("title", "name", "heading") if k in lower_keys), None)
        slug_key = next((lower_keys[k] for k in ("slug", "code", "alias") if k in lower_keys), None)
        url_key = next((lower_keys[k] for k in ("url", "href", "link", "path") if k in lower_keys), None)

        candidate_url = ""
        if url_key is not None and isinstance(obj[url_key], str):
            candidate_url = obj[url_key]
            for path in LIBRARY_PATH_RE.findall(candidate_url):
                add_discovery(store, path, source)
        if slug_key is not None and isinstance(obj[slug_key], str):
            slug = obj[slug_key].strip()
            if re.fullmatch(r"[A-Za-zА-Яа-яЁё0-9_.~-]{2,160}", slug):
                candidate_url = f"{LIBRARY_URL}/{slug}"
                add_discovery(store, candidate_url, source)

        if title_key is not None and (slug_key is not None or candidate_url):
            flattened = flatten_keys(obj)
            flattened["_source"] = source
            flattened["_candidate_url"] = canonical_url(candidate_url) if candidate_url else ""
            for dimension, value in context.items():
                flattened[f"_context_{dimension}"] = value
            records.append(flattened)

        for raw_key, value in obj.items():
            dimension = dimension_from_key(str(raw_key))
            if isinstance(value, Sequence) and not isinstance(value, (str, bytes, bytearray)):
                for child in value:
                    extract_urls_and_records_from_json(
                        child,
                        store,
                        source,
                        records,
                        inherited_context=context,
                        forced_dimension=dimension,
                    )
            else:
                extract_urls_and_records_from_json(
                    value,
                    store,
                    source,
                    records,
                    inherited_context=context,
                    forced_dimension=dimension if isinstance(value, Mapping) else None,
                )
        return

    if isinstance(obj, Sequence) and not isinstance(obj, (str, bytes, bytearray)):
        for value in obj:
            extract_urls_and_records_from_json(
                value,
                store,
                source,
                records,
                inherited_context=context,
                forced_dimension=forced_dimension,
            )


async def fetch_robots(client: PoliteClient) -> tuple[str, urllib.robotparser.RobotFileParser | None]:
    url = f"{BASE_URL}/robots.txt"
    try:
        response = await client.get(url)
        if response.status_code == 200:
            text = response.text
            parser = urllib.robotparser.RobotFileParser()
            parser.set_url(url)
            parser.parse(text.splitlines())
            return text, parser
    except Exception as exc:
        logging.debug("robots.txt unavailable: %s", exc)
    return "", None


async def discover_from_sitemaps(
    client: PoliteClient,
    store: MutableMapping[str, DiscoveryRecord],
    robots_text: str,
    raw_dir: Path,
) -> None:
    sitemap_urls = {
        f"{BASE_URL}/sitemap.xml",
        f"{BASE_URL}/sitemap_index.xml",
        f"{BASE_URL}/sitemap-index.xml",
        f"{BASE_URL}/sitemap/sitemap.xml",
    }
    for line in robots_text.splitlines():
        if line.lower().startswith("sitemap:"):
            sitemap_urls.add(line.split(":", 1)[1].strip())

    seen: set[str] = set()
    queue = list(sitemap_urls)
    while queue and len(seen) < 30:
        url = queue.pop(0)
        if url in seen:
            continue
        seen.add(url)
        try:
            response = await client.get(url)
        except Exception as exc:
            logging.debug("Sitemap failed %s: %s", url, exc)
            continue
        if response.status_code != 200 or not response.content:
            continue
        (raw_dir / f"sitemap_{len(seen):02d}.xml").write_bytes(response.content)
        try:
            root = ET.fromstring(response.content)
        except ET.ParseError:
            continue
        for loc in root.findall(".//{*}loc"):
            value = normalize_space(loc.text)
            if not value:
                continue
            if value.lower().endswith(".xml"):
                queue.append(value)
            elif is_library_url(value):
                add_discovery(store, value, "sitemap")


async def discover_from_wayback(
    client: PoliteClient,
    store: MutableMapping[str, DiscoveryRecord],
    raw_dir: Path,
) -> None:
    endpoint = "https://web.archive.org/cdx/search/cdx"
    for host in ("ai-russia.ru", "stage.ai-russia.ru"):
        params = {
            "url": f"{host}/library/*",
            "output": "json",
            "fl": "original,statuscode,mimetype,timestamp",
            "filter": "statuscode:200",
            "collapse": "urlkey",
        }
        try:
            response = await client.get(endpoint, params=params)
            if response.status_code != 200:
                continue
            data = response.json()
            (raw_dir / f"wayback_{host.replace('.', '_')}.json").write_text(
                json.dumps(data, ensure_ascii=False), encoding="utf-8"
            )
            if not isinstance(data, list) or len(data) < 2:
                continue
            header = data[0]
            try:
                original_idx = header.index("original")
            except ValueError:
                original_idx = 0
            for row in data[1:]:
                if isinstance(row, list) and len(row) > original_idx:
                    add_discovery(store, str(row[original_idx]), "wayback")
        except Exception as exc:
            logging.warning("Wayback discovery failed for %s: %s", host, exc)


async def discover_from_common_crawl(
    client: PoliteClient,
    store: MutableMapping[str, DiscoveryRecord],
    raw_dir: Path,
    indexes: int,
) -> None:
    try:
        response = await client.get("https://index.commoncrawl.org/collinfo.json")
        response.raise_for_status()
        collections = response.json()
    except Exception as exc:
        logging.warning("Common Crawl collection list failed: %s", exc)
        return

    selected = collections[: max(1, indexes)] if isinstance(collections, list) else []
    (raw_dir / "commoncrawl_collections.json").write_text(
        json.dumps(selected, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    for collection in selected:
        api = collection.get("cdx-api") if isinstance(collection, Mapping) else None
        if not api:
            continue
        for host in ("ai-russia.ru", "stage.ai-russia.ru"):
            params = {
                "url": f"{host}/library/*",
                "output": "json",
                "filter": "status:200",
                "collapse": "urlkey",
            }
            try:
                response = await client.get(str(api), params=params)
                if response.status_code != 200:
                    continue
                filename = safe_filename(f"cc_{collection.get('id','index')}_{host}") + ".jsonl"
                (raw_dir / filename).write_text(response.text, encoding="utf-8")
                for line in response.text.splitlines():
                    try:
                        row = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    url = row.get("url") if isinstance(row, Mapping) else None
                    if url:
                        add_discovery(store, str(url), f"commoncrawl:{collection.get('id','')}")
            except Exception as exc:
                logging.warning("Common Crawl query failed (%s, %s): %s", collection.get("id"), host, exc)


async def progressive_scroll(page: Page, rounds: int = 8) -> None:
    previous = -1
    stable = 0
    for _ in range(rounds):
        try:
            height = await page.evaluate("document.body.scrollHeight")
            await page.evaluate("window.scrollTo(0, document.body.scrollHeight)")
            await page.wait_for_timeout(500)
        except Exception:
            return
        if height == previous:
            stable += 1
            if stable >= 2:
                break
        else:
            stable = 0
        previous = height


async def click_load_more(page: Page, max_clicks: int = 15) -> None:
    pattern = re.compile(r"(?:показать|загрузить|ещ[её]|далее|more)", re.IGNORECASE)
    for _ in range(max_clicks):
        clicked = False
        try:
            candidates = page.get_by_role("button").filter(has_text=pattern)
            count = await candidates.count()
            for index in range(min(count, 10)):
                button = candidates.nth(index)
                if await button.is_visible() and await button.is_enabled():
                    await button.click()
                    await page.wait_for_timeout(500)
                    clicked = True
                    break
        except Exception:
            pass
        if not clicked:
            break


async def discover_with_browser(
    store: MutableMapping[str, DiscoveryRecord],
    records: list[dict[str, Any]],
    raw_dir: Path,
    *,
    headless: bool,
    user_agent: str,
    timeout_ms: int,
    max_pages: int,
) -> list[dict[str, Any]]:
    if async_playwright is None:
        logging.warning("Playwright unavailable; skipping browser/network discovery")
        return []

    endpoint_rows: list[dict[str, Any]] = []
    json_tasks: set[asyncio.Task[Any]] = set()
    response_counter = 0

    async with BrowserRenderer(
        headless=headless,
        concurrency=1,
        user_agent=user_agent,
        timeout_ms=timeout_ms,
    ) as renderer:
        assert renderer._context is not None
        page = await renderer._context.new_page()

        async def handle_response(response: Any) -> None:
            nonlocal response_counter
            request = response.request
            content_type = (response.headers.get("content-type") or "").lower()
            row = {
                "url": response.url,
                "status": response.status,
                "method": request.method,
                "resource_type": request.resource_type,
                "content_type": content_type,
                "post_data": request.post_data or "",
            }
            endpoint_rows.append(row)
            if "json" not in content_type and request.resource_type not in {"xhr", "fetch"}:
                return
            try:
                data = await response.json()
            except Exception:
                return
            response_counter += 1
            json_path = raw_dir / f"network_{response_counter:04d}.json"
            try:
                json_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
            except Exception:
                pass
            before = len(records)
            extract_urls_and_records_from_json(data, store, f"network:{response.url}", records)
            for record in records[before:]:
                record["_request_url"] = response.url
                record["_request_post_data"] = request.post_data or ""
                record["_discovery_page_url"] = page.url

        def schedule_response(response: Any) -> None:
            task = asyncio.create_task(handle_response(response))
            json_tasks.add(task)
            task.add_done_callback(json_tasks.discard)

        page.on("response", schedule_response)

        queue: list[str] = [LIBRARY_URL, *LEGACY_INDEX_URLS]
        queued = set(queue)
        visited: set[str] = set()

        while queue and len(visited) < max_pages:
            url = queue.pop(0)
            if url in visited:
                continue
            visited.add(url)
            logging.info("Browser discovery %d/%d: %s", len(visited), max_pages, url)
            try:
                await page.goto(url, wait_until="domcontentloaded")
                try:
                    await page.wait_for_load_state("networkidle", timeout=min(8000, timeout_ms))
                except Exception:
                    pass
                await progressive_scroll(page)
                await click_load_more(page)
                await progressive_scroll(page, rounds=4)
            except Exception as exc:
                logging.warning("Browser discovery page failed %s: %s", url, exc)
                continue

            # Links plus their visible text help distinguish taxonomy pages from card pages.
            try:
                anchors = await page.eval_on_selector_all(
                    "a[href]",
                    "els => els.map(a => ({href: a.href, text: (a.innerText || a.textContent || '').trim()}))",
                )
            except Exception:
                anchors = []

            for anchor in anchors:
                href = anchor.get("href", "") if isinstance(anchor, Mapping) else ""
                text = normalize_space(anchor.get("text", "")) if isinstance(anchor, Mapping) else ""
                if not href:
                    continue
                canonical = canonical_url(href)
                if is_legacy_index_url(canonical):
                    if canonical not in queued and len(queued) < max_pages * 4:
                        queued.add(canonical)
                        queue.append(canonical)
                    continue
                if not is_library_url(canonical):
                    continue
                add_discovery(store, canonical, f"browser-link:{url}")
                slug = slug_from_url(canonical).lower()
                looks_taxonomy = slug in CATEGORY_SLUG_HINTS or bool(re.search(r"\d+\s+сценари", text, re.I))
                if looks_taxonomy and canonical not in queued and len(queued) < max_pages * 4:
                    queued.add(canonical)
                    queue.append(canonical)

            # Nuxt/SPA state and JSON script tags.
            try:
                states = await page.evaluate(
                    """
                    () => {
                      const out = [];
                      for (const key of ['__NUXT__','__NEXT_DATA__','__INITIAL_STATE__','__APOLLO_STATE__']) {
                        if (window[key] !== undefined) {
                          try { out.push({key, value: JSON.parse(JSON.stringify(window[key]))}); } catch (_) {}
                        }
                      }
                      for (const el of document.querySelectorAll('script[type="application/json"],script#__NEXT_DATA__')) {
                        try { out.push({key: el.id || 'script-json', value: JSON.parse(el.textContent)}); } catch (_) {}
                      }
                      return out;
                    }
                    """
                )
                for state in states or []:
                    extract_urls_and_records_from_json(state, store, f"browser-state:{url}", records)
            except Exception:
                pass

        if json_tasks:
            await asyncio.gather(*list(json_tasks), return_exceptions=True)
        await page.close()

    return endpoint_rows


