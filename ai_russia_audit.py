def section_name(line: str) -> str | None:
    cleaned = normalize_space(line).lower().strip(" :.-—–")
    if not cleaned or len(cleaned) > 90:
        return None
    for canonical, aliases in SECTION_ALIASES.items():
        for alias in aliases:
            if cleaned == alias or cleaned.startswith(alias + ":"):
                return canonical
    return None


def parse_sections(lines: Sequence[str]) -> dict[str, str]:
    buckets: dict[str, list[str]] = defaultdict(list)
    current: str | None = None
    for raw in lines:
        line = normalize_space(raw)
        if not line:
            continue
        if SECTION_STOP_RE.fullmatch(line.strip(" :.-—–")):
            current = None
            continue
        label = section_name(line)
        if label is not None:
            current = label
            alias = next(a for a in SECTION_ALIASES[label] if line.lower().startswith(a))
            remainder = re.sub(
                r"^" + re.escape(alias),
                "",
                line,
                flags=re.IGNORECASE,
            ).strip(" :.-—–")
            if remainder:
                buckets[current].append(remainder)
            continue
        if current is not None:
            buckets[current].append(line)
    return {key: normalize_space(" ".join(values)) for key, values in buckets.items()}


def extract_inline_adopter(lines: Sequence[str]) -> str:
    """Recover cards where the UI renders `Acme, внедрившая кейс` as one line.

    Some historical pages put the company before the label, while newer pages render a normal
    label/value pair. This helper only accepts a narrow grammatical pattern to avoid guessing a
    company from ordinary prose.
    """
    for index, raw in enumerate(lines):
        line = normalize_space(raw)
        match = INLINE_ADOPTER_RE.match(line)
        if match:
            candidate = normalize_space(match.group("name")).strip(" :.-—–")
            if candidate.lower() not in {"компания", "организация", "клиент", "заказчик"} and is_nonempty(candidate):
                return candidate

        low = line.lower().strip(" :.-—–")
        if low in {"внедрившая кейс", "внедривший кейс", "реализовавшая кейс", "реализовавший кейс"} and index:
            candidate = normalize_space(lines[index - 1]).strip(" :.-—–")
            if section_name(candidate) is None and not SECTION_STOP_RE.fullmatch(candidate) and is_nonempty(candidate):
                return candidate
    return ""


def extract_title(soup: BeautifulSoup) -> str:
    for selector in ("h1", "main h2", "[itemprop='headline']"):
        node = soup.select_one(selector)
        if node:
            title = normalize_space(node.get_text(" ", strip=True))
            if title and title.lower() not in {"витрина ии-кейсов", "витрина кейсов"}:
                return re.sub(r"^\d{1,4}\s*[.)]\s*", "", title)
    for prop in (("property", "og:title"), ("name", "twitter:title")):
        node = soup.find("meta", attrs={prop[0]: prop[1]})
        if node and node.get("content"):
            title = normalize_space(node.get("content"))
            title = re.sub(r"\s+[—|-]\s+AI Russia.*$", "", title, flags=re.IGNORECASE)
            if title.lower() not in {"витрина ии-кейсов", "витрина кейсов"}:
                return title
    if soup.title:
        title = normalize_space(soup.title.get_text(" ", strip=True))
        title = re.sub(r"\s+[—|-]\s+AI Russia.*$", "", title, flags=re.IGNORECASE)
        return title
    return ""


def parse_card_html(
    html: str,
    url: str,
    *,
    discovery_sources: Iterable[str],
    status_code: int,
    fetch_method: str,
) -> Card | None:
    soup = BeautifulSoup(html, "lxml")
    for element in soup(["script", "style", "noscript", "svg"]):
        element.decompose()
    title = extract_title(soup)
    main = soup.select_one("main") or soup.body or soup
    lines = [normalize_space(value) for value in main.stripped_strings]
    lines = [line for line in lines if line]
    full_text = normalize_space(" ".join(lines))
    if not looks_like_card_text(full_text, title):
        return None

    sections = parse_sections(lines)
    if not is_nonempty(sections.get("adopter", "")):
        inline_adopter = extract_inline_adopter(lines)
        if inline_adopter:
            sections["adopter"] = inline_adopter
    visible_number = ""
    for line in lines[:40]:
        match = re.fullmatch(r"(\d{1,4})[.)]?", line)
        if match:
            visible_number = match.group(1)
            break
        match = re.match(r"^(\d{1,4})[.)]\s+", line)
        if match:
            visible_number = match.group(1)
            break

    external: list[str] = []
    tags: list[str] = []
    self_url = canonical_url(url)
    for anchor in main.select("a[href]"):
        href = urllib.parse.urljoin(url, str(anchor.get("href", "")))
        text = normalize_space(anchor.get_text(" ", strip=True))
        parsed = urllib.parse.urlsplit(href)
        host = parsed.netloc.lower().removeprefix("www.")
        if host and host not in {"ai-russia.ru", "stage.ai-russia.ru"}:
            if href not in external and not href.startswith(("mailto:", "tel:")):
                external.append(href)
        elif href and canonical_url(href) != self_url and parsed.path.startswith("/library/"):
            if text and 1 < len(text) < 80 and text not in tags:
                tags.append(text)

    return Card(
        url=self_url,
        slug=slug_from_url(self_url),
        title=title,
        visible_number=visible_number,
        full_text=full_text,
        problem=sections.get("problem", ""),
        solution=sections.get("solution", ""),
        technologies=sections.get("technologies", ""),
        results=sections.get("results", ""),
        business_effect=sections.get("business_effect", ""),
        social_effect=sections.get("social_effect", ""),
        image_effect=sections.get("image_effect", ""),
        adopter=sections.get("adopter", ""),
        developer=sections.get("developer", ""),
        team=sections.get("team", ""),
        sources_text=sections.get("sources", ""),
        tags=" | ".join(tags),
        external_links=" | ".join(external),
        discovery_sources=" | ".join(sorted(discovery_sources)),
        fetch_method=fetch_method,
        status_code=status_code,
        content_hash=normalized_text_hash(full_text),
    )


