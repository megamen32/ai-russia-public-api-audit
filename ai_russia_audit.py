def placement_reuse_rows(placements: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    grouped: dict[str, list[Mapping[str, Any]]] = defaultdict(list)
    for row in placements:
        url = normalize_space(row.get("url", ""))
        if url:
            grouped[url].append(row)
    output: list[dict[str, Any]] = []
    for url, rows in grouped.items():
        cells = {
            (
                normalize_space(row.get("industry", "")),
                normalize_space(row.get("business_function", "")),
                normalize_space(row.get("business_task", "")),
            )
            for row in rows
        }
        first = rows[0]
        output.append(
            {
                "url": url,
                "slug": first.get("slug", slug_from_url(url)),
                "title": first.get("title", ""),
                "grade": first.get("grade", ""),
                "source_family": first.get("source_family", ""),
                "placement_count": len(cells),
                "distinct_industries": len({cell[0] for cell in cells if cell[0]}),
                "distinct_functions": len({cell[1] for cell in cells if cell[1]}),
                "distinct_tasks": len({cell[2] for cell in cells if cell[2]}),
                "reused_across_cells": len(cells) > 1,
                "cells": " || ".join(" > ".join(part or "?" for part in cell) for cell in sorted(cells)),
            }
        )
    return sorted(output, key=lambda row: (-int(row["placement_count"]), str(row["url"])))

def extract_casebook_fingerprint(pdf_bytes: bytes) -> tuple[str, dict[str, Any]]:
    if fitz is None:
        return "", {"error": "PyMuPDF not installed"}
    document = fitz.open(stream=pdf_bytes, filetype="pdf")
    pages = [page.get_text("text") for page in document]
    text = "\n".join(pages)
    compact = normalize_space(text)
    intro = normalize_space("\n".join(pages[:4]))
    normalized = normalize_for_match(text)

    # In the designed PDF the labels and values are separate text boxes, so extraction order is
    # `решений отобрано ... 105 ... решений отобрано 100`, not necessarily `105 решений`.
    # Restrict count detection to the introduction, where both declared totals are printed.
    has_selected_label = "решений отобрано" in intro.lower()
    fingerprint = {
        "pages": document.page_count,
        "description_problem_headings": text.lower().count("описание проблемы"),
        "explicit_source_labels": len(re.findall(r"\bисточник\s*:", text, re.IGNORECASE)),
        "external_uri_annotations": sum(
            1 for page in document for link in page.get_links() if link.get("uri")
        ),
        "declared_classic_solutions": 105
        if has_selected_label and re.search(r"(?<!\d)105(?!\d)", intro)
        else None,
        "declared_genai_solutions": 100
        if has_selected_label and re.search(r"(?<!\d)100(?!\d)", intro)
        else None,
        "potential_effect_wording": bool(
            re.search(r"реальные\s*/\s*потенциально\s+достижимые\s+эффекты", compact, re.IGNORECASE)
        ),
        "sha256": hashlib.sha256(pdf_bytes).hexdigest(),
    }
    document.close()
    return normalized, fingerprint


def infer_adopter_from_deployment_text(card: Card) -> tuple[bool, str]:
    """Infer an adopter only from a sentence that also states actual operation/deployment.

    Product names in technology or consultation blocks are deliberately not enough. The exact
    triggering sentence is kept for human review.
    """
    for sentence in re.split(r"(?<=[.!?])\s+|\n+", card.full_text):
        sentence = normalize_space(sentence)
        if len(sentence) < 20 or not DEPLOYMENT_RE.search(sentence):
            continue
        organizations = [normalize_space(match.group(0)) for match in ORG_EVIDENCE_RE.finditer(sentence)]
        organizations = list(dict.fromkeys(value for value in organizations if value))
        if not organizations:
            continue
        if not card.adopter:
            card.adopter = "[inferred] " + " | ".join(organizations[:6])
        return True, sentence[:700]
    return False, ""


def classify_card(card: Card, casebook_normalized: str) -> None:
    title_norm = normalize_for_match(card.title)
    content_probe = normalize_for_match(" ".join((card.problem, card.solution)))
    card.title_in_casebook_pdf = bool(
        casebook_normalized and len(title_norm) >= 12 and title_norm in casebook_normalized
    )
    card.text_in_casebook_pdf = bool(
        casebook_normalized and len(content_probe) >= 100 and content_probe in casebook_normalized
    )
    if card.text_in_casebook_pdf:
        card.casebook_match_basis = "problem+solution exact normalized substring"
    elif card.title_in_casebook_pdf:
        card.casebook_match_basis = "title exact normalized substring"
    else:
        card.casebook_match_basis = ""

    slug_lower = card.slug.lower()
    casebook_match = card.text_in_casebook_pdf or card.title_in_casebook_pdf
    if casebook_match and re.fullmatch(r"genai\d+", slug_lower):
        card.source_family = "casebook_2024_genai"
    elif casebook_match and re.fullmatch(r"ml\d+", slug_lower):
        card.source_family = "casebook_2024_classic"
    elif casebook_match:
        card.source_family = "casebook_2024_match"
    elif re.fullmatch(r"(?:genai|ml)\d+", slug_lower):
        card.source_family = "catalog_prefix_unmatched"
    else:
        card.source_family = "legacy_or_other"

    explicit_adopter = is_nonempty(card.adopter) and len(card.adopter) >= 3
    inferred, excerpt = infer_adopter_from_deployment_text(card)
    card.adopter_inferred_from_text = inferred and not explicit_adopter
    card.adopter_evidence_excerpt = excerpt
    card.has_named_adopter = explicit_adopter or inferred

    card.has_verified_badge = bool(VERIFIED_BADGE_RE.search(card.full_text))
    card.has_deployment_claim = bool(DEPLOYMENT_RE.search(card.full_text))
    card.is_announcement_only = bool(ANNOUNCEMENT_RE.search(card.full_text)) and not card.has_deployment_claim

    results_heading_re = re.compile(r"(?:^|[\n.!?]\s*)(?:результаты|полученные результаты|результат)\s*[:]?", re.I)
    business_heading_re = re.compile(r"(?:^|[\n.!?]\s*)(?:бизнес[- ]эффект|экономический эффект)\s*[:]?", re.I)
    card.has_results_heading = bool(results_heading_re.search(card.full_text))
    card.has_business_effect_heading = bool(business_heading_re.search(card.full_text))

    result_scope = normalize_space(" ".join((card.results, card.business_effect)))
    card.has_actual_result_language = bool(ACTUAL_RESULT_RE.search(result_scope))
    card.has_metric_anywhere = bool(METRIC_RE.search(card.full_text))
    card.has_metric_in_results = bool(METRIC_RE.search(result_scope))
    card.has_year = bool(YEAR_RE.search(card.full_text))
    card.has_team = is_nonempty(card.team) and len(card.team) >= 8
    card.has_technical_detail = bool(TECH_RE.search(" ".join((card.technologies, card.solution))))
    card.has_source_section = is_nonempty(card.sources_text)
    card.has_external_source = card.has_source_section or bool(card.external_links)
    card.potential_marker_count = len(POTENTIAL_RE.findall(card.full_text))
    card.empty_results = not is_nonempty(card.results)
    card.empty_business_effect = not is_nonempty(card.business_effect)
    card.consultant_or_vendor_only = bool(
        CONSULTANT_ONLY_RE.search(card.full_text)
        and not card.has_named_adopter
        and not card.has_deployment_claim
    )

    score = 0
    reasons: list[str] = []

    if explicit_adopter:
        score += 4
        reasons.append("explicit named adopter field")
    elif inferred:
        score += 3
        reasons.append("organization named in an actual-deployment sentence")
    if card.has_deployment_claim:
        score += 3
        reasons.append("actual deployment/operation wording")
    if card.has_metric_in_results and card.has_actual_result_language:
        score += 4
        reasons.append("quantified actual result in results/effect section")
    elif card.has_metric_in_results:
        score += 1
        reasons.append("number in results/effect section, actuality unclear")
    if card.has_year:
        score += 1
        reasons.append("dated scope")
    if card.has_team:
        score += 2
        reasons.append("named project team")
    if card.has_technical_detail:
        score += 1
        reasons.append("technical detail")
    if card.has_verified_badge:
        score += 3
        reasons.append("legacy expert-verification badge/text")
    if card.has_source_section:
        score += 2
        reasons.append("explicit source section")
    elif card.external_links:
        score += 1
        reasons.append("external link present (may still be a vendor link)")

    casebook_origin = card.source_family.startswith("casebook_2024") or card.source_family == "catalog_prefix_unmatched"
    if casebook_origin and not card.has_named_adopter:
        score -= 4
        reasons.append("casebook/catalogue origin without named adopter")
    if card.is_announcement_only:
        score -= 4
        reasons.append("announcement/future pilot, not completed deployment")
    if card.potential_marker_count >= 2 and not card.has_deployment_claim:
        score -= 2
        reasons.append("mostly modal/potential wording")
    if card.empty_results and card.empty_business_effect:
        score -= 2
        reasons.append("result and business-effect sections empty/unparsed")
    if card.consultant_or_vendor_only:
        score -= 3
        reasons.append("consultants/vendors listed without adopter or operation")

    card.grade_score = score
    source_backed = card.has_source_section or card.has_verified_badge
    if (
        card.has_named_adopter
        and card.has_deployment_claim
        and card.has_metric_in_results
        and card.has_actual_result_language
        and source_backed
        and score >= 10
    ):
        card.grade = "A_source_backed_implemented"
    elif (
        (card.has_named_adopter or card.has_verified_badge)
        and card.has_deployment_claim
        and (card.has_actual_result_language or card.has_metric_in_results or card.has_team or card.has_year)
        and score >= 6
    ):
        card.grade = "B_documented_implemented"
    elif card.has_named_adopter or (card.has_verified_badge and card.has_deployment_claim):
        card.grade = "C_named_but_weakly_evidenced"
    elif casebook_origin or card.is_announcement_only or card.consultant_or_vendor_only or card.potential_marker_count >= 2:
        card.grade = "D_scenario_or_potential"
    else:
        card.grade = "E_unclear"
    card.grade_reasons = "; ".join(reasons)

